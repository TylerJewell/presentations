// Renders a film (the main film at ../index.html, or another folder with its own index.html, such as a snippet) to a
// silent MP4, with act chapters and an SRT.
//   node website/demo/mock/render/render.mjs [--from=S] [--to=S] [--fps=30] [--scale=1] [--workers=4] [--name=akka-demo]
//                                    [--no-encode] [--force] [--voice] [--no-mix] [--roomtone] [--film=<folder>]
// --film renders that folder's index.html, reads its durations.json, writes its voice.js and puts the output in
// <folder>/out; the music and effects always come from this film's sound/.
// --voice times every scene to its narration clip (durations.json beside the mock, from demo/sample/tts.mjs), captures
// into out/frames-voice, and writes <name>.mp4 with the narration mastered in (default name akka-demo),
// <name>-silent.mp4 and <name>.srt from the real line timings. --no-mix stops after the silent picture and the
// caption file, for a film whose own script adds the sound (film/sound.mjs).
// Frames land in out/frames, or out/frames-<scale> for a draft scale (resumable: existing frames are skipped). A range or scale other than the full
// 1920x1080 run is named <name>-draft so it never overwrites the final render.
import { createRequire } from "node:module";
import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { join, dirname, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { spawnSync } from "node:child_process";

const require = createRequire("C:/Users/tyler/ai-console/kalix-console/apps/stories/package.json");
const { chromium } = require("playwright");

const HERE = dirname(fileURLToPath(import.meta.url));
let FRAMES;
const arg = (k, d) => process.argv.find((a) => a.startsWith(`--${k}=`))?.slice(k.length + 3) ?? d;
const FILM = resolve(arg("film", join(HERE, "..")));
const OUT = FILM === resolve(HERE, "..") ? join(HERE, "out") : join(FILM, "out");
const flag = (k) => process.argv.includes(`--${k}`);
const FPS = +arg("fps", 30), SCALE = +arg("scale", 1), WORKERS = +arg("workers", 4);
const VOICE = flag("voice");
const ROOMTONE = flag("roomtone");
FRAMES = join(OUT, (SCALE === 1 ? "frames" : `frames-${SCALE}`) + (VOICE ? "-voice" : ""));
const URL_ = pathToFileURL(join(FILM, "index.html")).href + "?capture=1" + (VOICE ? "&voice=1" : "");

// The player reads clip lengths from voice.js, since a page opened from file:// cannot fetch durations.json.
const durations = VOICE ? JSON.parse(readFileSync(join(FILM, "durations.json"), "utf8")) : null;
if (VOICE) {
  const secs = Object.fromEntries(Object.entries(durations).map(([id, d]) => [id, +d.seconds.toFixed(3)]));
  mkdirSync(OUT, { recursive: true });
  writeFileSync(join(FILM, "voice.js"),
    "/* Generated by render/render.mjs --voice from durations.json: each scene's narration clip, in seconds. */\n" +
    `window.MOCK_VOICE = ${JSON.stringify(secs, null, 2)};\n`);
}

for (const bin of ["ffmpeg", "ffprobe"]) {
  if (spawnSync(bin, ["-version"]).status !== 0) { console.error(`${bin} is not on PATH`); process.exit(1); }
}

const launch = async () => {
  const opts = { headless: true, args: ["--force-device-scale-factor=" + SCALE, "--hide-scrollbars"] };
  try { return await chromium.launch(opts); } catch { return await chromium.launch({ ...opts, channel: "msedge" }); }
};
const open = async (browser) => {
  const ctx = await browser.newContext({ viewport: { width: 1920, height: 1080 }, deviceScaleFactor: SCALE });
  const page = await ctx.newPage();
  page.on("pageerror", (e) => console.error("page error:", e.message));
  await page.goto(URL_);
  await page.evaluate(() => document.fonts.ready);
  await page.waitForFunction(() => window.mock && window.mock.total > 0, null, { timeout: 60000 });
  return page;
};
const settle = (page, t) => page.evaluate((t) => new Promise((res) => {
  window.mock.seek(t);
  requestAnimationFrame(() => requestAnimationFrame(res));
}), t);

mkdirSync(FRAMES, { recursive: true });
const browser = await launch();
const main = await open(browser);

// Scene list, plus each scene's caption lines as the player lays them out (Mock.Caption.lines).
const { total, scenes, acts } = await main.evaluate(() => ({
  total: window.mock.total, scenes: window.mock.scenes, acts: window.MOCK_ACTS,
}));
// Voiced frames depend on the scene timing the player derives from the clips, so a new timing invalidates them.
const stamp = join(FRAMES, "timing.json");
const timing = JSON.stringify(scenes.map((s) => [s.id, s.start, s.duration]));
if (VOICE && (!existsSync(stamp) || readFileSync(stamp, "utf8") !== timing)) {
  readdirSync(FRAMES).forEach((f) => rmSync(join(FRAMES, f)));
  writeFileSync(stamp, timing);
}
// Cursor clicks, for the click sound: the moments a ripple appears, swept through the timeline in the page.
const clicks = await main.evaluate((total) => {
  const out = []; let was = 0;
  for (let t = 0; t < total; t += 1 / 60) {
    window.mock.seek(t);
    const o = Math.max(0, ...[...document.querySelectorAll(".mk-ripple")].map((r) => +r.style.opacity || 0));
    if (o > 0.6 && was <= 0.6) out.push(+t.toFixed(3));
    was = o;
  }
  return out;
}, total);
const captions = [];
for (const s of scenes) {
  await settle(main, s.start + 0.01);
  // A film that shows headlines draws no narration, so its caption file is the narration a sentence at a time,
  // each from the moment the paced clip speaks it.
  const lines = await main.evaluate(() => {
    const s = Mock.stageInfo.scene, marks = window.MOCK_PACING && window.MOCK_PACING.marks && window.MOCK_PACING.marks[s.id];
    const sents = s.caption.split(/(?<=[.!?])\s+/), t0 = (s.cardDur || 0) + 0.35;
    if (window.MOCK_FILM && window.MOCK_FILM.headlines && s.clip != null && marks && marks.length === sents.length)
      return sents.map((text, i) => ({ text, a: t0 + marks[i][1] }));
    return Mock.Caption.lines.map((l) => ({ text: l.el.textContent, a: l.a }));
  });
  // a voiced line ends with its clip; a silent one stays until the caption leaves
  const end = s.clip != null ? s.card + 0.35 + s.clip : s.duration - 0.5;
  lines.forEach((l, i) => captions.push({
    from: s.start + l.a, to: s.start + (lines[i + 1] ? lines[i + 1].a : end), text: l.text,
  }));
}

const from = +arg("from", 0), to = Math.min(+arg("to", total), total);
const first = Math.round(from * FPS), last = Math.round(to * FPS); // frames [first, last)
const full = first === 0 && last === Math.round(total * FPS) && SCALE === 1;
const name = arg("name", VOICE ? "akka-demo" : "akka-demo-silent") + (full ? "" : "-draft");
const path = (i) => join(FRAMES, `f${String(i).padStart(6, "0")}.jpg`);

if (flag("force")) readdirSync(FRAMES).filter((f) => f.endsWith(".jpg")).forEach((f) => rmSync(join(FRAMES, f)));
const todo = [];
for (let i = first; i < last; i++) if (!existsSync(path(i))) todo.push(i);
console.log(`${total} s total; frames ${first}..${last - 1} (${last - first}), ${todo.length} to capture, scale ${SCALE}, ${WORKERS} workers`);

if (todo.length) {
  const pages = [main];
  while (pages.length < Math.min(WORKERS, todo.length)) pages.push(await open(browser));
  const size = Math.ceil(todo.length / pages.length);
  const t0 = Date.now();
  let done = 0;
  await Promise.all(pages.map(async (page, w) => {
    for (const i of todo.slice(w * size, (w + 1) * size)) {
      await settle(page, i / FPS);
      await page.screenshot({
        path: path(i), type: "jpeg", quality: 92,
        clip: { x: 0, y: 0, width: 1920, height: 1080 },
      });
      if (++done % 100 === 0 || done === todo.length) {
        const el = (Date.now() - t0) / 1000;
        console.log(`${done}/${todo.length} frames, ${(done / el).toFixed(1)} fps, eta ${Math.round((todo.length - done) / (done / el))} s`);
      }
    }
  }));
  console.log(`captured ${todo.length} frames in ${((Date.now() - t0) / 1000).toFixed(1)} s`);
}
await browser.close();
if (flag("no-encode")) process.exit(0);

// Chapters: one per act, at the act's first scene; clipped to the rendered range.
const ms = (s) => Math.round((s - from) * 1000);
const starts = [];
for (const s of scenes) if (!starts.length || starts[starts.length - 1].act !== s.act) starts.push({ act: s.act, at: s.start });
const meta = [";FFMETADATA1"];
starts.forEach((c, i) => {
  const end = i + 1 < starts.length ? starts[i + 1].at : total;
  if (end <= from || c.at >= to) return;
  const a = acts[c.act] || {};
  const title = a.title ? `${a.label || a.kicker} · ${a.title}` : a.label || `Act ${c.act}`;
  meta.push("[CHAPTER]", "TIMEBASE=1/1000", `START=${Math.max(0, ms(Math.max(c.at, from)))}`, `END=${ms(Math.min(end, to))}`, `title=${title}`);
});
writeFileSync(join(OUT, `${name}.chapters.txt`), meta.join("\n"));

// Captions as SRT, shifted to the rendered range.
const ts = (s) => {
  const t = Math.round(s * 1000), p = (n, w = 2) => String(n).padStart(w, "0");
  return `${p(Math.floor(t / 3600000))}:${p(Math.floor(t / 60000) % 60)}:${p(Math.floor(t / 1000) % 60)},${p(t % 1000, 3)}`;
};
const cues = captions.filter((c) => c.to > from && c.from < to)
  .map((c, i) => `${i + 1}\n${ts(Math.max(c.from, from) - from)} --> ${ts(Math.min(c.to, to) - from)}\n${c.text}\n`);
writeFileSync(join(OUT, `${name}.srt`), cues.join("\n"));

const mp4 = join(OUT, VOICE ? `${name}-silent.mp4` : `${name}.mp4`);
const r = spawnSync("ffmpeg", ["-y", "-hide_banner", "-loglevel", "error", "-stats",
  "-framerate", String(FPS), "-start_number", String(first), "-i", join(FRAMES, "f%06d.jpg"),
  "-i", join(OUT, `${name}.chapters.txt`), "-map_metadata", "1", "-map_chapters", "1",
  "-c:v", "libx264", "-crf", "16", "-preset", "medium", "-pix_fmt", "yuv420p", "-vf", "scale=trunc(iw/2)*2:trunc(ih/2)*2",
  "-frames:v", String(last - first), "-an", "-movflags", "+faststart", mp4], { stdio: "inherit" });
if (r.status !== 0) { console.error("ffmpeg failed"); process.exit(1); }

if (VOICE && !flag("no-mix")) {
  // Each clip starts 0.35 s after its scene's card, as its caption does. The Professional voice is clean (noise floor
  // about -83 dB), so clips are mixed as generated, without denoising. Each line fades over 0.55 s from just before
  // its speech ends (the last point above -40 dB), so the final breath tapers instead of stopping dead. The mix is measured first and then levelled linearly
  // (one fixed gain) to -16 LUFS integrated, true peak -1.8 dBTP so it stays under -1.5 dBTP after AAC encoding;
  // dynamic levelling would ride the gain down on each line's tail.
  // With ../sound/music.mp3 present, the bed sits about 18 dB under the voice between lines and fades a further 18 dB
  // from 0.6 s before each line until its speech ends, then rises over 1 s, so the last word sinks into it, on a fixed curve from the line timings (a compressor would let it
  // swell in every pause). A wide cut around 2.5 kHz keeps it out of the voice's presence band. A whoosh and a swell mark each chapter card, and a soft
  // click marks each cursor click. The sound files are generated with ElevenLabs (see README "Voice").
  const speechEnd = (f, secs) => {
    const ends = [...spawnSync("ffmpeg", ["-hide_banner", "-i", f, "-af", "silencedetect=n=-40dB:d=0.08", "-f", "null", "-"], { encoding: "utf8" }).stderr.matchAll(/silence_start: ([\d.]+)/g)].map((m) => +m[1]);
    const last = ends.length ? ends[ends.length - 1] : secs;
    return secs - last < 0.8 ? last : secs;
  };
  const lines = scenes.filter((s) => s.clip != null).map((s) => {
    const { file, seconds: secs } = durations[s.id];
    return { file, secs, speech: speechEnd(file, secs), ms: Math.round((s.start + s.card + 0.35) * 1000) };
  });
  const args = ["-y", "-hide_banner", "-loglevel", "info", "-i", mp4];
  lines.forEach((l) => args.push("-i", l.file));
  const SOUND = join(HERE, "..", "sound"), withSound = existsSync(join(SOUND, "music.mp3"));
  const lufs = (f) => +/I:\s+(-?[\d.]+) LUFS/.exec(spawnSync("ffmpeg", ["-hide_banner", "-i", f, "-af", "ebur128", "-f", "null", "-"], { encoding: "utf8" }).stderr.split("Summary")[1])[1];
  const cues = [];
  if (withSound) {
    for (const s of scenes) if (s.card > 0 && s.start > 0) cues.push(["whoosh", s.start - 0.45, -27], ["card", s.start + 0.05, -26]);
    for (const t of clicks) cues.push(["click", t - 0.01, -30]);
    const n0 = lines.length + 1;
    args.push("-i", join(SOUND, "music.mp3"));
    cues.forEach(([k]) => args.push("-i", join(SOUND, `${k}.mp3`)));
    cues.forEach((c, i) => (c.push(n0 + 1 + i)));
  }
  const gain = {};
  if (withSound) for (const k of ["music", "whoosh", "card", "click"]) gain[k] = lufs(join(SOUND, `${k}.mp3`));
  const voiceL = withSound ? lines.reduce((a, l) => a + lufs(l.file), 0) / lines.length : 0;
  const taper = (l) => `afade=t=out:st=${Math.max(0, l.speech - 0.12).toFixed(3)}:d=0.55:curve=qsin,apad=pad_dur=0.5`;
  const delays = lines.map((l, i) => `[${i + 1}:a]${taper(l)},adelay=${l.ms}|${l.ms}[a${i}]`);
  let bus = `${delays.join(";")};${lines.map((_, i) => `[a${i}]`).join("")}amix=inputs=${lines.length}:normalize=0:dropout_transition=0`;
  if (withSound) {
    const n0 = lines.length + 1, end = total;
    const duck = lines.map((l) => { const a = l.ms / 1000, b = a + l.speech; return `clip(min((t-${(a - 1.1).toFixed(2)})/0.5,(${(b + 1.15).toFixed(2)}-t)/1.0),0,1)`; })
      .reduce((acc, e) => `max(${acc},${e})`);
    bus += `[vb];[${n0}:a]atrim=0:${end},volume=${(voiceL - 18 - gain.music).toFixed(1)}dB,equalizer=f=2500:t=o:w=1.6:g=-6,` +
      `volume='pow(10,-18*${duck}/20)':eval=frame,afade=t=in:d=2.5,afade=t=out:st=${(end - 4).toFixed(2)}:d=4[md];` +
      cues.map(([k, t, l, n], i) => `[${n}:a]volume=${(l - gain[k]).toFixed(1)}dB,adelay=${Math.round(t * 1000)}|${Math.round(t * 1000)}[x${i}]`).join(";") + (cues.length ? ";" : "") +
      `[vb][md]${cues.map((_, i) => `[x${i}]`).join("")}amix=inputs=${2 + cues.length}:normalize=0:dropout_transition=0`;
  }
  // A continuous, barely audible room tone under the whole film: the bed ducks to near silence under the narration, and
  // without it each voice entry and exit meets dead air and the edit points can be heard.
  if (ROOMTONE) bus += `[vm];anoisesrc=color=pink:amplitude=0.0015:duration=${total}:sample_rate=48000,highpass=f=70,lowpass=f=7000[rt];[vm][rt]amix=inputs=2:normalize=0:dropout_transition=0`;
  bus += `,atrim=start=${from},asetpts=PTS-STARTPTS,apad`;
  const LN = "loudnorm=I=-16:TP=-1.8:LRA=11";
  const pass1 = spawnSync("ffmpeg", [...args, "-filter_complex", `${bus},${LN}:print_format=json[a]`, "-map", "[a]", "-t", String(to - from), "-f", "null", "-"], { encoding: "utf8" });
  const js = JSON.parse(pass1.stderr.slice(pass1.stderr.lastIndexOf("{"), pass1.stderr.lastIndexOf("}") + 1));
  const mix = `${bus},${LN}:measured_I=${js.input_i}:measured_TP=${js.input_tp}:measured_LRA=${js.input_lra}:measured_thresh=${js.input_thresh}:offset=${js.target_offset}:linear=true[a]`;
  const voiced = join(OUT, `${name}.mp4`);
  const m = spawnSync("ffmpeg", [...args.map((a) => (a === "info" ? "error" : a)), "-filter_complex", mix, "-map", "0:v", "-map", "[a]", "-map_metadata", "0", "-map_chapters", "0",
    "-c:v", "copy", "-c:a", "aac", "-b:a", "192k", "-ar", "48000", "-movflags", "+faststart", "-shortest", voiced], { stdio: "inherit" });
  if (m.status !== 0) { console.error("ffmpeg (voice) failed"); process.exit(1); }
  console.log(voiced);
}
const probe = spawnSync("ffprobe", ["-v", "error", "-show_entries", "format=duration:stream=width,height", "-of", "csv=p=0", mp4], { encoding: "utf8" });
console.log(`${mp4}\n${probe.stdout.trim().replace(/\n/g, " | ")} (duration s)`);
