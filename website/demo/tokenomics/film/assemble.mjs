// Builds each scene's narration from one clip per sentence (sentences/audio, from demo/sample/tts.mjs --dir=sentences).
//   node demo/tokenomics/film/assemble.mjs
// Every sentence is its own clip, so a pause can only fall between sentences. Each clip is cut from just before its
// first word's attack to just after its last word's decay, with a short fade at each cut, because the voice opens on
// an intake and trails off after the last word, and both read as a breath after a pause. Levels are measured against
// the clip's own loud speech. `pause` seconds of silence go between sentences.
// Writes audio/paced/<scene>.wav, durations.json (what the renderer reads) and pacing.js (window.MOCK_PACING: the tail
// lengths and each sentence's word range and time span, in seconds from the start of the scene's clip).
import { spawnSync } from "node:child_process";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const cfg = JSON.parse(readFileSync(join(ROOT, "film", "pacing.config.json"), "utf8"));
const lines = JSON.parse(readFileSync(join(ROOT, "narration.json"), "utf8"));
const clips = JSON.parse(readFileSync(join(ROOT, "sentences", "durations.json"), "utf8"));
const OUT = join(ROOT, "audio", "paced");
mkdirSync(OUT, { recursive: true });

const HOP = 0.01;
const ATTACK = 14, DECAY = 40, LEAD = 0.045, TAIL_AFTER = 0.07, FADE_IN = 0.02, FADE_OUT = 0.09;

const level = (f) => {
  const r = spawnSync("ffmpeg", ["-v", "error", "-i", f, "-ac", "1", "-ar", "22050", "-f", "f32le", "-"], { maxBuffer: 1 << 28 });
  const x = new Float32Array(r.stdout.buffer, r.stdout.byteOffset, Math.floor(r.stdout.length / 4));
  const hop = Math.round(22050 * HOP), db = [];
  for (let i = 0; i + hop <= x.length; i += hop) {
    let e = 0;
    for (let j = i; j < i + hop; j++) e += x[j] * x[j];
    db.push(10 * Math.log10(e / hop + 1e-12));
  }
  const sorted = [...db].sort((a, b) => a - b);
  return { db, peak: sorted[Math.floor(sorted.length * 0.98)] };
};

// The span of one clip that holds speech: from just before the first word's attack to just after the last word's decay.
const speech = (file, secs) => {
  const env = level(file);
  let on = -1, off = -1;
  for (let i = 0; i + 2 < env.db.length; i++) if (env.db[i] > env.peak - ATTACK && env.db[i + 1] > env.peak - ATTACK && env.db[i + 2] > env.peak - ATTACK) { on = i; break; }
  for (let i = env.db.length - 1; i >= 1; i--) if (env.db[i] > env.peak - DECAY && env.db[i - 1] > env.peak - DECAY) { off = i; break; }
  if (on < 0 || off < on) return [0, secs];
  return [Math.max(0, on * HOP - LEAD), Math.min(secs, (off + 1) * HOP + TAIL_AFTER)];
};

const durations = {}, marks = {};
for (const [id, text] of Object.entries(lines)) {
  const sents = text.split(/(?<=[.!?])\s+/);
  const counts = sents.map((x) => x.split(/\s+/).length);
  const inputs = [], parts = [], order = [];
  let clock = 0, w = 0;
  marks[id] = [];
  sents.forEach((_, k) => {
    const clip = clips[`${id}.${k + 1}`];
    if (!clip) throw new Error(`${id}: no clip for sentence ${k + 1}`);
    const [a, b] = speech(clip.file, clip.seconds), len = b - a;
    inputs.push("-i", clip.file);
    parts.push(`[${k}:a]aformat=sample_rates=44100:channel_layouts=mono,atrim=${a.toFixed(4)}:${b.toFixed(4)},asetpts=PTS-STARTPTS,` +
      `afade=t=in:d=${FADE_IN}:curve=qsin,afade=t=out:st=${Math.max(0, len - FADE_OUT).toFixed(4)}:d=${FADE_OUT}:curve=qsin[s${k}]`);
    order.push(`[s${k}]`);
    if (k < sents.length - 1) { parts.push(`aevalsrc=0:d=${cfg.pause}:s=44100:c=mono[p${k}]`); order.push(`[p${k}]`); }
    marks[id].push([w, +clock.toFixed(3), +(clock + len).toFixed(3)]);
    clock += len + cfg.pause;
    w += counts[k];
  });
  const file = join(OUT, `${id}.wav`);
  const r = spawnSync("ffmpeg", ["-y", "-loglevel", "error", ...inputs, "-filter_complex", `${parts.join(";")};${order.join("")}concat=n=${order.length}:v=0:a=1[a]`, "-map", "[a]", "-c:a", "pcm_s16le", file], { encoding: "utf8" });
  if (r.status !== 0) throw new Error(`${id}: ffmpeg failed\n${r.stderr}`);
  const dur = +spawnSync("ffprobe", ["-v", "error", "-show_entries", "format=duration", "-of", "csv=p=0", file], { encoding: "utf8" }).stdout;
  durations[id] = { file, seconds: dur, paced: true };
}
writeFileSync(join(ROOT, "durations.json"), JSON.stringify(durations, null, 2));
writeFileSync(join(ROOT, "pacing.js"),
  "/* Generated by film/assemble.mjs. tail and cardTail are seconds after a line; marks[id] lists each sentence as\n" +
  "   [first word index, speech start, speech end] in seconds from the start of the scene's clip. */\n" +
  `window.MOCK_PACING = ${JSON.stringify({ tail: cfg.tail, cardTail: cfg.cardTail, marks })};\n`);

// Running time: each scene is its chapter card, the 0.35 s lead, its clip and its tail; the last scene keeps the player's own fit.
const cards = new Set(["1.1", "2.1", "3.1", "4.1"]);
const ids = Object.keys(durations);
let t = 0;
ids.forEach((id, i) => { t += (cards.has(id) ? 2.6 : 0) + 0.35 + durations[id].seconds + (i === ids.length - 1 ? 1.2 : cards.has(ids[i + 1]) ? cfg.cardTail : cfg.tail); });
console.log(`approx running time ${t.toFixed(1)} s (${Math.floor(t / 60)}:${String(Math.round(t % 60)).padStart(2, "0")})`);
